<#
  Builds the PiPusher client for Raspberry Pi and packages client + server into .\dist

    .\build.ps1                  # build the version in the VERSION file
    .\build.ps1 -Bump patch      # 1.1.0 -> 1.1.1, then build   (bug fixes)
    .\build.ps1 -Bump minor      # 1.1.0 -> 1.2.0, then build   (new features)
    .\build.ps1 -Bump major      # 1.1.0 -> 2.0.0, then build

  The version is stamped into the server (server\inc\version.php), the client binaries and all
  package names. Builds of other versions already in .\dist are kept.

  Output:
    dist\pipusher-client-<ver>.tar.gz          copy to the Pi, unpack, run install.sh (also contains windows\)
    dist\pipusher-client-windows-<ver>.zip     the Windows 10/11 client: unpack, run install.ps1
    dist\pipusher-client-windows7-8-<ver>.zip  the same for Windows 7/8/8.1 (built with Go 1.20)
    dist\pipusher-server-<ver>.zip             upload to your PHP web host
    dist\pipusher-windows-amd64-<ver>.exe      the client for local testing on Windows
#>
param([ValidateSet('', 'patch', 'minor', 'major')][string]$Bump = '')
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot

# ---------------------------------------------------------------- version
$versionFile = Join-Path $root 'VERSION'
$Version = (Get-Content $versionFile -Raw).Trim()
if ($Version -notmatch '^(\d+)\.(\d+)\.(\d+)$') { throw "VERSION must look like 1.2.3, got '$Version'" }
if ($Bump) {
    $maj, $min, $pat = [int]$Matches[1], [int]$Matches[2], [int]$Matches[3]
    switch ($Bump) {
        'major' { $maj++; $min = 0; $pat = 0 }
        'minor' { $min++; $pat = 0 }
        'patch' { $pat++ }
    }
    $Version = "$maj.$min.$pat"
    [IO.File]::WriteAllText($versionFile, $Version)
}
$utf8 = New-Object System.Text.UTF8Encoding($false)
[IO.File]::WriteAllText("$root\server\inc\version.php",
    "<?php`n// Generated by build.ps1 from the VERSION file - do not edit.`ndefine('PP_VERSION', '$Version');`n", $utf8)
Write-Host "PiPusher $Version" -ForegroundColor Cyan

$go = Join-Path $root 'tools\go\bin\go.exe'
if (-not (Test-Path $go)) {
    $cmd = Get-Command go -ErrorAction SilentlyContinue
    if (-not $cmd) { throw 'Go not found. Run .\setup-tools.ps1 first.' }
    $go = $cmd.Source
}
Write-Host "Using $(& $go version)"

# The player is shared: the server copy is the source of truth, the client embeds a copy.
Copy-Item "$root\server\assets\player\player.js", "$root\server\assets\player\player.css" "$root\client\web\" -Force

$dist = Join-Path $root 'dist'
$work = Join-Path $dist '_build'
New-Item -ItemType Directory -Force $dist | Out-Null
if (Test-Path $work) { Remove-Item -Recurse -Force $work }
Get-ChildItem $dist -File -Filter "*-$Version.*" | Remove-Item -Force   # rebuild of the same version
$pkgName = "pipusher-client-$Version"
$pkg = Join-Path $work $pkgName
New-Item -ItemType Directory -Force $pkg | Out-Null

$targets = @(
    @{ GOOS = 'linux'; GOARCH = 'arm64'; GOARM = ''; Out = "$pkg\pipusher-linux-arm64" },
    @{ GOOS = 'linux'; GOARCH = 'arm'; GOARM = '7'; Out = "$pkg\pipusher-linux-armv7" },
    @{ GOOS = 'linux'; GOARCH = 'amd64'; GOARM = ''; Out = "$pkg\pipusher-linux-amd64" },
    @{ GOOS = 'windows'; GOARCH = 'amd64'; GOARM = ''; Out = "$dist\pipusher-windows-amd64-$Version.exe" }
)
# Go 1.21+ only builds for Windows 10/11; Go 1.20 is the last release that runs on Windows 7/8/8.1.
$go120 = Join-Path $root 'tools\go1.20\bin\go.exe'
if (-not (Test-Path $go120)) { throw 'Go 1.20 (for the Windows 7/8.1 client) not found. Run .\setup-tools.ps1 first.' }
$legacy = Join-Path $work 'windows-legacy'
New-Item -ItemType Directory -Force $legacy | Out-Null
$legacyTargets = @(
    @{ GOOS = 'windows'; GOARCH = 'amd64'; GOARM = ''; Out = "$legacy\pipusher.exe" },
    @{ GOOS = 'windows'; GOARCH = '386'; GOARM = ''; Out = "$legacy\pipusher-386.exe" }
)
$saved = @{ GOOS = $env:GOOS; GOARCH = $env:GOARCH; GOARM = $env:GOARM; CGO_ENABLED = $env:CGO_ENABLED }
Push-Location "$root\client"
try {
    $env:CGO_ENABLED = '0'
    & $go vet ./...
    if ($LASTEXITCODE) { throw 'go vet failed' }
    foreach ($t in $targets) {
        $env:GOOS = $t.GOOS; $env:GOARCH = $t.GOARCH; $env:GOARM = $t.GOARM
        Write-Host "Building $($t.GOOS)/$($t.GOARCH)$(if ($t.GOARM) { 'v' + $t.GOARM })"
        & $go build -trimpath -ldflags "-s -w -X main.version=$Version" -o $t.Out .
        if ($LASTEXITCODE) { throw "build failed for $($t.GOOS)/$($t.GOARCH)" }
    }
    foreach ($t in $legacyTargets) {
        $env:GOOS = $t.GOOS; $env:GOARCH = $t.GOARCH; $env:GOARM = $t.GOARM
        Write-Host "Building $($t.GOOS)/$($t.GOARCH) for Windows 7/8.1 (Go 1.20)"
        & $go120 build '-modfile=go.legacy.mod' -trimpath -ldflags "-s -w -X main.version=$Version" -o $t.Out .
        if ($LASTEXITCODE) { throw "legacy build failed for $($t.GOOS)/$($t.GOARCH)" }
    }
} finally {
    Pop-Location
    foreach ($k in $saved.Keys) { Set-Item "env:$k" $saved[$k] }
}

# Shell scripts must have LF line endings to run on the Pi.
foreach ($f in Get-ChildItem "$root\client\install") {
    $text = [IO.File]::ReadAllText($f.FullName) -replace "`r`n", "`n"
    [IO.File]::WriteAllText((Join-Path $pkg $f.Name), $text, $utf8)
}
$readme = @"
PiPusher client $Version

On the Raspberry Pi (Raspberry Pi OS Bookworm or newer, desktop edition):

  tar xzf pipusher-client-$Version.tar.gz
  cd pipusher-client-$Version
  sudo bash install.sh --server https://your-site.example/pipusher/ --key YOUR_REGISTRATION_KEY
  sudo reboot

Updating: unpack the new version and run  sudo bash install.sh  again (keeps the config and cache).
Options: --name "Screen name"  --user pi  --no-autologin  --no-kiosk
Config:  /etc/pipusher/pipusher.json      Cache: /var/lib/pipusher
Logs:    journalctl -u pipusher -f        Remove: sudo bash uninstall.sh [--purge]

Windows 10/11: see windows\README.txt (also available as pipusher-client-windows-$Version.zip).
"@ -replace "`r`n", "`n"
[IO.File]::WriteAllText("$pkg\README.txt", $readme, $utf8)

# Windows client: the exe plus install/kiosk scripts, with CRLF line endings.
$win = Join-Path $pkg 'windows'
New-Item -ItemType Directory -Force $win | Out-Null
Copy-Item "$dist\pipusher-windows-amd64-$Version.exe" "$win\pipusher.exe"
foreach ($f in Get-ChildItem "$root\client\windows" -File) {
    $text = [IO.File]::ReadAllText($f.FullName) -replace "`r?`n", "`r`n"
    [IO.File]::WriteAllText((Join-Path $win $f.Name), $text, $utf8)
}

$tar = "$env:SystemRoot\System32\tar.exe"
& $tar -czf "$dist\pipusher-client-$Version.tar.gz" -C $work $pkgName
if ($LASTEXITCODE) { throw 'tar failed' }
$winName = "pipusher-client-windows-$Version"
Rename-Item $win $winName
& $tar -a -cf "$dist\$winName.zip" -C $pkg $winName
if ($LASTEXITCODE) { throw 'windows zip failed' }

# Windows 7/8/8.1 client: the same scripts with the Go 1.20 exes (64-bit, plus 32-bit for install.ps1 to pick).
$legacyName = "pipusher-client-windows7-8-$Version"
Get-ChildItem "$pkg\$winName" -File | Where-Object Name -ne 'pipusher.exe' | Copy-Item -Destination $legacy
$text = [IO.File]::ReadAllText("$legacy\README.txt") -replace 'Windows 10/11', 'Windows 7, 8 and 8.1 (32- and 64-bit)' `
    -replace 'Needs Google Chrome \(or Microsoft Edge\)\.', "`$0 Chrome 109 is the last version for these Windows versions:`r`nit works, but gets no more updates."
[IO.File]::WriteAllText("$legacy\README.txt", $text, $utf8)
Rename-Item $legacy $legacyName
& $tar -a -cf "$dist\$legacyName.zip" -C $work $legacyName
if ($LASTEXITCODE) { throw 'windows 7/8 zip failed' }

# Server package: everything except runtime data and local config.
$stage = Join-Path $work 'server\pipusher'
Copy-Item "$root\server" $stage -Recurse
Get-ChildItem "$stage\data" -Force | Where-Object { $_.Name -ne '.htaccess' } | Remove-Item -Recurse -Force
Remove-Item "$stage\config.php" -ErrorAction SilentlyContinue
# tar (not Compress-Archive, which writes backslash paths on Windows PowerShell 5.1) for a Linux-friendly zip.
& $tar -a -cf "$dist\pipusher-server-$Version.zip" -C (Split-Path $stage) pipusher
if ($LASTEXITCODE) { throw 'zip failed' }
Remove-Item -Recurse -Force $work

Write-Host "`nDone:" -ForegroundColor Green
Get-ChildItem $dist -File -Filter "*-$Version.*" | ForEach-Object { '  {0,-40} {1,10:N0} bytes' -f $_.Name, $_.Length }
